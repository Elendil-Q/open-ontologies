fun bit_cut_integer k =
  (if ((k : IntInf.int) = (0 : IntInf.int)) then ((0 : IntInf.int), false)
    else let
           val (r, s) =
             IntInf.divMod (IntInf.abs k, IntInf.abs (2 : IntInf.int));
         in
           ((if IntInf.< ((0 : IntInf.int), k) then r
              else IntInf.- (IntInf.~ r, s)),
             ((s : IntInf.int) = (1 : IntInf.int)))
         end);

fun char_of_integer k = let
                          val (q0, b0) = bit_cut_integer k;
                          val (q1, b1) = bit_cut_integer q0;
                          val (q2, b2) = bit_cut_integer q1;
                          val (q3, b3) = bit_cut_integer q2;
                          val (q4, b4) = bit_cut_integer q3;
                          val (q5, b5) = bit_cut_integer q4;
                          val (q6, b6) = bit_cut_integer q5;
                          val (_, a) = bit_cut_integer q6;
                        in
                          Chara (b0, b1, b2, b3, b4, b5, b6, a)
                        end;

fun char_of_nat x = (char_of_integer o integer_of_nat) x;

fun chr_of_nat n = char_of_nat n;

fun nat_of_chr c = nat_of_char c;

fun body_lenient beta k j [] = NONE
  | body_lenient beta k j (b :: bs) =
    (case iptriple beta b of NONE => SOME R_binding_incomplete
      | SOME t =>
        (if member
              (equal_prod equal_rdf_term
                (equal_prod equal_rdf_term equal_rdf_term))
              t k
          then body_lenient beta k (suc j) bs else SOME (R_premise_unknown j)));

fun check_step_lenient r k s =
  (if less_eq_nat (size_list r) (sidx s) then SOME R_index_out_of_range
    else let
           val ra = nth r (sidx s);
           val b = sbind s;
         in
           (case body_lenient b k zero_nat (rbody ra)
             of NONE =>
               (if equal_option
                     (equal_prod equal_rdf_term
                       (equal_prod equal_rdf_term equal_rdf_term))
                     (iptriple b (rhead ra)) (SOME (sconcl s))
                 then NONE else SOME R_head_mismatch)
             | SOME a => SOME a)
         end);

fun check_from_lenient r k j [] = NONE
  | check_from_lenient r k j (s :: ss) =
    (case check_step_lenient r k s
      of NONE =>
        check_from_lenient r
          (insert
            (equal_prod equal_rdf_term
              (equal_prod equal_rdf_term equal_rdf_term))
            (sconcl s) k)
          (suc j) ss
      | SOME e => SOME (j, e));

fun check_cert_lenient r g ss = check_from_lenient r (Set g) zero_nat ss;

